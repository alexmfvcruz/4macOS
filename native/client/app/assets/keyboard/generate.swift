// Run here: swift generate.swift > keyboard_pixels.h
// User PNGs fitted without cropping. Pixels use premultiplied alpha.
import Foundation
import CoreGraphics
import ImageIO
let width = 64, height = 51
print("// Generated by generate.swift from adjacent original PNGs.\n#pragma once\n#include <cstdint>\nnamespace keyboard_art {\nconstexpr int width = 64, height = 51;")
for name in ["inactive", "active"] {
    let source = CGImageSourceCreateWithURL(URL(fileURLWithPath: "\(name).png") as CFURL, nil)!
    let image = CGImageSourceCreateImageAtIndex(source, 0, nil)!
    var bytes = [UInt8](repeating: 0, count: width * height * 4)
    bytes.withUnsafeMutableBytes { buffer in
        let context = CGContext(data: buffer.baseAddress, width: width, height: height, bitsPerComponent: 8, bytesPerRow: width * 4, space: CGColorSpace(name: CGColorSpace.sRGB)!, bitmapInfo: CGImageAlphaInfo.premultipliedLast.rawValue | CGBitmapInfo.byteOrder32Big.rawValue)!
        context.interpolationQuality = .high
        context.draw(image, in: CGRect(x: 0, y: 0, width: width, height: height))
    }
    print("const std::uint32_t \(name)[] = {")
    for y in 0..<height {
        print((0..<width).map { x in
            let i = (y * width + x) * 4
            let pixel = UInt32(bytes[i+3]) << 24 | UInt32(bytes[i]) << 16 | UInt32(bytes[i+1]) << 8 | UInt32(bytes[i+2])
            return String(format: "0x%08x", pixel)
        }.joined(separator: ",") + ",")
    }
    print("};")
}
print("}")
