#!/usr/bin/env python3
"""Generate the native resource table of the client from TClient.rc (C4).

Windows links TClient.rc into the executable. The native build embeds the
same files and strings in a C++ table that registers itself with
fourstory::resources (native/client/compat/include/fourstory_kernel32.h).

Handled statements: CURSOR, ICON, SHADER, TEXT (file resources) and
STRINGTABLE. A CURSOR file that starts with "RIFF" becomes RT_ANICURSOR (21),
as the resource compiler does (VERIFIED in the Windows x64 build:
runtime/legacy/c0/TClient-x64-b2.exe, ids 186, 187 and 1153); other cursors are
RT_GROUP_CURSOR (12) and icons RT_GROUP_ICON (14) with the whole file as data.
DIALOG, VERSIONINFO, DESIGNINFO and TEXTINCLUDE are not generated (README).

  gen_resources.py OUTPUT.cpp [SHADERS.cpp]

SHADERS.cpp: the bytecode table of D3DXAssembleShader (native/client/
reference/shaders, assembled on Windows by the original D3DX9_43.dll), keyed
by the SHA-256 of the shader source bytes.
"""
import re, sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
CLIENT = ROOT / 'source/4Story 5.0 Source Files/Client/TClient'
RC = CLIENT / 'TClient.rc'
FILE_RESOURCE = re.compile(r'(\w+)\s+(CURSOR|ICON|SHADER|TEXT)\s+"([^\"]+)"$')

def input_paths():
    import json
    paths = [Path(__file__), RC, CLIENT/'resource.h']
    for line in RC.read_text(encoding='latin-1').splitlines():
        match = FILE_RESOURCE.match(line.strip())
        if match: paths.append(CLIENT/match.group(3).replace('\\\\','/'))
    ref = ROOT/'native/client/reference/shaders'
    manifest = ref/'manifest.json'
    paths.append(manifest)
    paths.extend(ref/(row['shader']+'.bin') for row in json.loads(manifest.read_text())['shaders'])
    return paths

if sys.argv[1:] == ['--list-inputs']:
    import json
    print(json.dumps([str(p) for p in input_paths()]))
    raise SystemExit(0)


ids = {}
for line in (CLIENT / 'resource.h').read_text(encoding='latin-1').splitlines():
    m = re.match(r'#define\s+(\w+)\s+(\d+)', line)
    if m: ids[m.group(1)] = int(m.group(2))
# MFC string ids used in TClient.rc (afxres.h).
ids.setdefault('AFX_IDS_APP_TITLE', 0xE000)
ids.setdefault('AFX_IDS_IDLEMESSAGE', 0xE001)

def number(token):
    if token.isdigit(): return int(token)
    if token not in ids: raise SystemExit(f'unknown resource id {token}')
    return ids[token]

def rc_string(text):
    """Decode an .rc string literal body (Latin-1 bytes of code page 1252/949)."""
    out, i = bytearray(), 0
    raw = text.encode('latin-1')
    while i < len(raw):
        c = raw[i]
        if c == 0x5C and i + 1 < len(raw):  # backslash
            n = raw[i + 1]; i += 2
            out += {ord('n'): b'\n', ord('t'): b'\t', ord('r'): b'\r', ord('0'): b'\0', 0x5C: b'\\', ord('"'): b'"'}.get(n, bytes([0x5C, n]))
            continue
        if c == 0x22 and i + 1 < len(raw) and raw[i + 1] == 0x22: out.append(0x22); i += 2; continue
        out.append(c); i += 1
    return bytes(out)

text = RC.read_text(encoding='latin-1')
resources = []  # (type_name or None, type_id, id, bytes, origin)
TYPES = {'CURSOR': 12, 'ICON': 14}
in_strings = False
for line in text.splitlines():
    s = line.strip()
    if s.startswith('STRINGTABLE'): in_strings = True; continue
    if in_strings:
        if s == 'END': in_strings = False; continue
        m = re.match(r'(\w+)\s+"(.*)"$', s)
        if m: resources.append((None, 6, number(m.group(1)), rc_string(m.group(2)), 'STRINGTABLE ' + m.group(1)))
        continue
    m = FILE_RESOURCE.match(s)
    if not m: continue
    name, kind, file = m.groups()
    data = (CLIENT / file.replace('\\\\', '/')).read_bytes()
    if kind in TYPES:
        type_id = 21 if kind == 'CURSOR' and data[:4] == b'RIFF' else TYPES[kind]
        resources.append((None, type_id, number(name), data, f'{kind} {name} {file}'))
    else:
        resources.append((kind, 0, number(name), data, f'{kind} {name} {file}'))

out = ['// Generated by native/client/app/gen_resources.py from TClient.rc. Do not edit.',
       '#include <windows.h>', 'namespace {']
for i, (_, _, _, data, origin) in enumerate(resources):
    out.append(f'// {origin}')
    out.append(f'const unsigned char r{i}[] = {{' + ','.join(str(b) for b in data) + (',' if data else '') + '0};')
out.append('const fourstory::resources::Resource table[] = {')
for i, (type_name, type_id, rid, data, _) in enumerate(resources):
    tn = f'"{type_name}"' if type_name else 'nullptr'
    out.append(f'    {{{tn}, {type_id}u, nullptr, {rid}u, r{i}, {len(data)}u}},')
out.append('};')
out.append('struct Register { Register() { fourstory::resources::add(table, sizeof(table) / sizeof(table[0])); } } register_table;')
out.append('}')
Path(sys.argv[1]).write_text('\n'.join(out) + '\n')
print(f'{len(resources)} resources from {RC.name}')

if len(sys.argv) > 2:
    import hashlib, json
    ref = ROOT / 'native/client/reference/shaders'
    manifest = json.loads((ref / 'manifest.json').read_text())
    out = ['// Generated by native/client/app/gen_resources.py from native/client/reference/shaders. Do not edit.',
           '#include <cstddef>', 'namespace fourstory { namespace d3dx {',
           'struct ShaderCode { unsigned char source_sha256[32]; const unsigned char* code; std::size_t size; const char* name; };']
    for i, s in enumerate(manifest['shaders']):
        code = (ref / (s['shader'] + '.bin')).read_bytes()
        if hashlib.sha256(code).hexdigest() != s['code_sha256']: raise SystemExit('bytecode hash differs: ' + s['shader'])
        out.append(f'static const unsigned char c{i}[] = {{' + ','.join(str(b) for b in code) + '};')
    out.append('extern const ShaderCode shader_codes[] = {')
    for i, s in enumerate(manifest['shaders']):
        digest = ','.join(str(b) for b in bytes.fromhex(s['source_sha256']))
        out.append(f'    {{{{{digest}}}, c{i}, sizeof(c{i}), "{s["shader"]}"}},')
    out.append('};')
    out.append(f'extern const std::size_t shader_code_count = {len(manifest["shaders"])};')
    out.append('}}')
    Path(sys.argv[2]).write_text('\n'.join(out) + '\n')
    print(f'{len(manifest["shaders"])} shader bytecodes')
