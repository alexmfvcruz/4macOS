#!/usr/bin/env python3
"""Generate explicit portable dump field visitors from the original loader uses.

Generated output is reviewed and compiled on both platforms. This is a source
inventory helper, not a proof that every field is serialized. Reference-ID
exceptions and helper types are explicit below; no raw structure memory dump.
"""
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[4]
CHART = ROOT/'source/4Story 5.0 Source Files/Lib/Own/TChart/TChart'
def clean(path):
    return re.sub(r'/\*.*?\*/|//[^\r\n]*', '', path.read_bytes().decode('latin1'), flags=re.S)
header, source, public = clean(CHART/'TChartType.h'), clean(CHART/'TChart.cpp'), clean(CHART/'TChart.h')
def body_at(s, start):
    pos=s.index('{',start)+1;begin=pos;depth=1
    while depth:
        depth+=(s[pos]=='{')-(s[pos]=='}');pos+=1
    return s[begin:pos-1]
records={}
for m in re.finditer(r'(?m)^struct\s+(tag\w+)\s*\{',header):
    body=body_at(header,m.start());level=0;fields=[]
    for line in body.splitlines():
        # Only class-scope declarations, not constructor or destructor accesses.
        if level==0:
            match=re.match(r'\s*(\w+)\s+(\*\s*)?(\w+)\s*(\[[^;]+\])?\s*;\s*$',line)
            if match:fields.append((match[1],match[3]))
        level+=line.count('{')-line.count('}')
    records[m[1]]=fields
aliases={}
for tag,alias,pointer in re.findall(r'typedef\s+struct\s+(tag\w+)\s+(\w+)\s*,\s*\*(\w+)\s*;',header):
    aliases[alias]=tag;aliases[pointer]=tag
used={name:set() for name in records}
for m in re.finditer(r'\b(?:void|BOOL)\s+CTChart::(Init\w+|ReadTNPC)\s*\(',source):
    body=body_at(source,m.start());variables={}
    for typ,var in re.findall(r'\b(\w+)\s*(?:\*|&)?\s+(\w+)\s*(?=[;=,\)])',body):
        if typ in aliases:variables[var]=aliases[typ]
    # ReadTNPC's pointer is a function parameter, not a local declaration.
    if m[1]=='ReadTNPC':variables['pTNPC']='tagTNPC'
    for var,field in re.findall(r'\b(\w+)\s*(?:->|\.)\s*(\w+)',body):
        if var in variables and variables[var] in used:used[variables[var]].add(field)
# Entire initialized CPU aggregates and map-key members; these are also loaded
# through global array expressions or constructed from read local values.
full={'tagTCLOTH','tagTMANTLECOORD','tagTMANTLECOORDKEY','tagTMANTLEDETAILKEY',
      'tagTITEMGRADEVISUALKEY','tagTRPS','tagTARENA','tagTEQUIPCREATECHAR','tagTSKILLUPGRADEINFO'}
extra={'tagTSKILL':{'m_vTFUNCTION','m_vTARROWDIR','m_vTUPGRADEINFO'},
       'tagTUNITFOG':{'m_pTGLOBAL','m_vTLOCAL'},'tagTMAPINFO':{'m_mapTNODE'},
       'tagTDETAILINFO':{'m_pTEXT'},'tagTPOPUPMENU':{'m_vTPOPUP'},
       'tagTMANTLECOORDINFO':{'m_strMeshName','m_vUV1','m_vUV2','m_vUV3'},
       'tagTQUEST':{'m_vTTERM','m_vTREWARD'},'tagTQCLASS':{'m_strNAME','m_dwClassID'},
       'tagTHELP':{'m_vPage'},'tagTTITLEGROUP':{'m_vTITLE'}}
for tag,fields in extra.items():used[tag].update(fields)
# Resolve runtime references by stable table IDs, not by object addresses or
# recursively walking cyclic portal graphs. Pointer fields with encoded asset
# identifiers are treated separately by the generic opaque-type visitor.
refs={'tagTNPC':{'m_pTNPC':'m_wID','m_pTPOPUP':'m_dwID'},
      'tagTMONTEMP':{'m_pTPOPUP':'m_dwID'},
      'tagTNPCPORTAL':{'m_pTPORTAL':'m_wPortalID'}}
# Fields used by downstream algorithms but not retained by a loader must not
# be read from newly allocated records (e.g. pursuit/UI runtime flags).
out='// Generated by generate_startup_fields.py; review field schema before handoff.\n'
for tag in records:
    out+='void visit(const Context&,const string&,'+tag+' const&);\n'
out+='\n'
for tag,fields in records.items():
    out+='void visit(const Context& c,const string& f,'+tag+' const& p){\n'
    selected=[name for _,name in fields if tag in full or name in used[tag]]
    for name in selected:
        if name=='m_vTHUMB' and tag=='tagTREGIONINFO':
            out+='    for(BYTE country:{BYTE(TCONTRY_D),BYTE(TCONTRY_C),BYTE(TCONTRY_B)})visit(c,f+".m_vTHUMB["+to_string(country)+"]",p.m_vTHUMB[country]);\n'
            continue
        if name=='m_vTUPGRADEINFO' and tag=='tagTSKILL':
            out+='    visit(c,f+".upgrade.present",p.m_vTUPGRADEINFO!=nullptr);\n'
            out+='    if(p.m_vTUPGRADEINFO)for(BYTE level:skillLevels[p.m_wSkillID])if(level>0&&level<=p.m_bMaxLevel)visit(c,f+".upgrade["+to_string(level)+"]",p.m_vTUPGRADEINFO[level-1]);\n'
            continue
        if name=='m_pTEXT' and tag=='tagTDETAILINFO':
            out+='    for(BYTE i=0;i<p.m_bCount;++i)visit(c,f+".text["+to_string(i)+"]",p.m_pTEXT[i]);\n'
            continue
        if name in ['m_ID','m_vID'] and tag in ['tagTAUCTIONTREE','tagTPORTALLINK']:continue
        if name in refs.get(tag,{}):
            idfield=refs[tag][name]
            out+='    visit(c,f+".'+name+'.present",p.'+name+'!=nullptr);\n'
            out+='    if(p.'+name+')visit(c,f+".'+name+'.id",p.'+name+'->'+idfield+');\n'
        else:out+='    visit(c,f+".'+name+'",p.'+name+');\n'
    if tag=='tagTAUCTIONTREE':out+='    visit(c,f+".m_ID.dwValue",p.m_ID.dwValue);\n'
    if tag=='tagTPORTALLINK':out+='    visit(c,f+".id",p.m_vID.m_dwID);\n'
    out+='}\n'
# Expose exactly the initialized TChart public tables to the reference dump.
roots=[]
for typ,name,dim in re.findall(r'\bstatic\s+(\w+)\s+(m_\w+)\s*(\[[^;]+\])?\s*;',public):
    if name in ['m_pTWORDCURSE','m_vTNAMECURSE','m_vTCHATCURSE','m_TNATIONOPTION','m_vTAUCTIONTREE','m_mapTDynamicHelp','CustomStrings']:continue
    roots.append(name)
out+='\nvoid dumpStartup(){\n'
for name in sorted(roots):
    if name=='m_mapTPORTALLINK':
        out+='    visit(Context{"m_mapTPORTALLINK","0"},"count",CTChart::m_mapTPORTALLINK.size());\n'
        out+='    for(const auto& entry:CTChart::m_mapTPORTALLINK)visit(Context{"m_mapTPORTALLINK",to_string(entry.first)},"value",*entry.second);\n'
        continue
    out+='    visit(Context{"'+name+'","0"},"value",CTChart::'+name+');\n'
out+='}\n'
(ROOT/'native/client/tests/dump/startup_fields.inc').write_text(out)
print('Generated',len(records),'record visitors and',len(roots),'table roots')
