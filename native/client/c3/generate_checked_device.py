#!/usr/bin/env python3
"""Generate real-device forwarding overrides; no device operation is simulated."""
import importlib.util
from pathlib import Path
import re
import sys
ROOT = Path(__file__).resolve().parents[3]
spec = importlib.util.spec_from_file_location('c2_declarations', ROOT/'native/client/device/generate_stubs.py')
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)
methods = module.methods((ROOT/'native/client/d3d9/include/d3d9.h').read_text(), 'IDirect3DDevice9')
lines = ['// Generated by generate_checked_device.py from the shared d3d9.h.']
for ret, name, params in methods:
    if name in {'QueryInterface', 'AddRef', 'Release'}:
        continue
    names = [re.findall(r'[A-Za-z_][A-Za-z0-9_]*', p)[-1] for p in params.split(',')] if params and params != 'void' else []
    call = f'real_->{name}({", ".join(names)})'
    if ret == 'HRESULT':
        body = ('if(before_draw)before_draw(real_); ' if name.startswith('Draw') else '') + f'HRESULT hr={call}; observe(hr,"{name}");'
        if name.startswith('Draw'):
            body += ' if(SUCCEEDED(hr))++draw_calls;'
        body += ' return hr;'
    elif ret == 'void':
        body = call+';'
    else:
        body = 'return '+call+';'
    lines.append(f'{ret} STDMETHODCALLTYPE {name}({params}) override {{ {body} }}')
target = Path(sys.argv[1]) if len(sys.argv)>1 else Path(__file__).with_name('checked_device.inc')
target.write_text('\n'.join(lines)+'\n')
