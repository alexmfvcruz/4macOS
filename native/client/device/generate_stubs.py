#!/usr/bin/env python3
"""Generate the not-executed methods of the empty device from the shared d3d9.h.

Every method that empty_device.cpp does not implement by hand is emitted as an
override that counts the call and reports failure (HRESULT methods return
D3DERR_NOTAVAILABLE; other methods return 0 or nothing). Output: stubs.inc,
one macro per interface: FOURSTORY_STUBS_<Interface>.
"""
import re, sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
HEADER = HERE.parent / 'd3d9' / 'include' / 'd3d9.h'
IMPLEMENTED = {
    'IDirect3DDevice9': {'QueryInterface','AddRef','Release','TestCooperativeLevel','GetDeviceCaps',
                         'CreateTexture','CreateVertexBuffer','CreateIndexBuffer','CreateOffscreenPlainSurface',
                         'GetAvailableTextureMem','EvictManagedResources'},
    'IDirect3DTexture9': {'QueryInterface','AddRef','Release','GetDevice','GetPriority','SetPriority','PreLoad','GetType',
                          'SetLOD','GetLOD','GetLevelCount','GetLevelDesc','GetSurfaceLevel','LockRect','UnlockRect','AddDirtyRect'},
    'IDirect3DSurface9': {'QueryInterface','AddRef','Release','GetDevice','GetPriority','SetPriority','PreLoad','GetType',
                          'GetContainer','GetDesc','LockRect','UnlockRect'},
    'IDirect3DVertexBuffer9': {'QueryInterface','AddRef','Release','GetDevice','GetPriority','SetPriority','PreLoad','GetType',
                               'Lock','Unlock','GetDesc'},
    'IDirect3DIndexBuffer9': {'QueryInterface','AddRef','Release','GetDevice','GetPriority','SetPriority','PreLoad','GetType',
                              'Lock','Unlock','GetDesc'},
}
# 'Buffer' serves the vertex and index buffer template; both interfaces have
# the same members apart from GetDesc.
IMPLEMENTED['Buffer'] = IMPLEMENTED['IDirect3DVertexBuffer9']
INHERIT = {'Buffer': ['IUnknown','IDirect3DResource9','IDirect3DVertexBuffer9'],
           'IDirect3DTexture9': ['IUnknown','IDirect3DResource9','IDirect3DBaseTexture9','IDirect3DTexture9'],
           'IDirect3DSurface9': ['IUnknown','IDirect3DResource9','IDirect3DSurface9'],
           'IDirect3DVertexBuffer9': ['IUnknown','IDirect3DResource9','IDirect3DVertexBuffer9'],
           'IDirect3DIndexBuffer9': ['IUnknown','IDirect3DResource9','IDirect3DIndexBuffer9'],
           'IDirect3DDevice9': ['IUnknown','IDirect3DDevice9']}

def methods(text, interface):
    if interface == 'IUnknown':
        return [('HRESULT','QueryInterface','REFIID riid, void** ppvObject'),('ULONG','AddRef',''),('ULONG','Release','')]
    m = re.search(r'DECLARE_INTERFACE_\(' + interface + r',\s*\w+\)\s*\{(.*?)\n\};', text, re.S)
    if not m: sys.exit(f'interface {interface} not found')
    out = []
    for decl in re.findall(r'STDMETHOD_?\((.*?)\)\s*\((.*?)\)\s*PURE;', m.group(1), re.S):
        head, params = decl
        parts = [p.strip() for p in head.split(',')]
        ret, name = (parts[0], parts[1]) if len(parts) == 2 else ('HRESULT', parts[0])
        params = re.sub(r'\s+', ' ', params).strip()
        params = re.sub(r'^THIS_?\s*', '', params).strip()
        if params:
            named = []
            for i, p in enumerate(x.strip() for x in params.split(',')):
                words = re.findall(r'[A-Za-z_][A-Za-z0-9_]*', p)
                if len(words) == 1 and words[0] != 'void':  # type only, e.g. "D3DPRIMITIVETYPE"
                    p = f'{p} unnamed{i}'
                named.append(p)
            params = ', '.join(named)
        out.append((ret, name, params))
    return out

def main():
    text = HEADER.read_text(encoding='latin-1')
    lines = ['// Generated by generate_stubs.py from native/client/d3d9/include/d3d9.h. Do not edit.']
    for interface, chain in INHERIT.items():
        seen, body = set(), []
        for base in chain:
            for ret, name, params in methods(text, base):
                if name in seen or name in IMPLEMENTED[interface]: seen.add(name); continue
                seen.add(name)
                pnames = [re.split(r'[\s\*&]+', p.strip())[-1] for p in params.split(',')] if params else []
                unused = ' '.join(f'(void){n};' for n in pnames if n and n != 'void')
                if ret == 'HRESULT': result = f'return not_executed("{interface}::{name}");'
                elif ret == 'void': result = f'(void)not_executed("{interface}::{name}");'
                else: result = f'(void)not_executed("{interface}::{name}"); return {ret}();'
                body.append(f'    {ret} {name}({params}) override {{ {unused} {result} }}')
        if interface == 'Buffer':  # name from the instance: vertex or index buffer
            body = [re.sub(r'not_executed\("Buffer::(\w+)"\)', r'not_executed(this->stub_name("\1"))', b) for b in body]
        lines.append(f'#define FOURSTORY_STUBS_{interface} \\')
        lines.append(' \\\n'.join(body))
        lines.append('')
    target = Path(sys.argv[1]) if len(sys.argv) > 1 else HERE / 'stubs.inc'
    target.write_text('\n'.join(lines) + '\n')
    print('wrote', target)

if __name__ == '__main__':
    main()
